import assert from 'node:assert/strict';
import { evaluateSession, initialSkill, median, slope, declineAlert } from './adaptive.ts';
const event = (session, correct, responseMs = 1000) => ({ session, correct, errorType: 'none', method: 'tap', responseMs, difficulty: 2 });
assert.equal(median([3, 1, 2]), 2);
assert.equal(median([100, 2, 1, 3]), 2.5);
assert.equal(median([]), null);
let state = initialSkill();
const bad = Array.from({ length: 4 }, (_, i) => event('a', false)).concat(Array.from({ length: 4 }, (_, i) => event('b', false)));
state = evaluateSession(state, bad);
assert.equal(state.knob, 1);
assert.equal(state.decision, 'down');
assert.equal(state.recent.length, 8);
state.baselines.tap = Array(8).fill(1000);
state = evaluateSession(state, Array.from({ length: 8 }, () => event('c', true)));
assert.equal(state.knob, 2);
assert.equal(state.baselines.tap.length, 16);
const before = state;
assert.deepEqual(evaluateSession(state, [{ ...event('d', true), errorType: 'recognition', correct: null }]), before);
state = evaluateSession(state, [{ ...event('d', true), method: 'voice', responseMs: 9000 }]);
assert.deepEqual(state.baselines.voice, [9000]);
assert.ok(state.baselines.tap.length <= 21);
assert.equal(slope([1, 2, 3]), 1);
assert.equal(declineAlert([90, 85, 80, 75, 70, 65, 60, 55]), true);
assert.equal(declineAlert([90, 90, 90, 90, 90, 90, 90, 0]), false);
assert.equal(declineAlert([90, 80, 70]), false);
assert.equal(declineAlert([70, 75, 80, 85, 80, 85, 90, 95]), false);
console.log('adaptive checks passed: separate baselines, recognition exclusion, one-knob changes and sustained slopes');
